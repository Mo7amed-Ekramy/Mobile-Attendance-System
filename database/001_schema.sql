    CREATE TABLE assessment_results (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        assessment_id bigint NOT NULL,
        enrollment_id bigint NOT NULL,
        offering_id bigint NOT NULL,
        score numeric(9,2),
        state text NOT NULL DEFAULT 'unrecorded' CHECK (state IN ('unrecorded', 'recorded', 'excused')),
        visibility text NOT NULL DEFAULT 'draft' CHECK (visibility IN ('draft', 'published')),
        feedback text,
        revision integer NOT NULL DEFAULT 1 CHECK (revision > 0),
        updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (assessment_id, offering_id) REFERENCES assessments(id, offering_id),
        FOREIGN KEY (enrollment_id, offering_id) REFERENCES enrollments(id, offering_id),
