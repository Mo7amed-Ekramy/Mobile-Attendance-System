    CREATE FUNCTION validate_result_score() RETURNS trigger LANGUAGE plpgsql AS $function$
    DECLARE maximum numeric;
    BEGIN
        SELECT max_points INTO maximum FROM attendance.assessments WHERE id = NEW.assessment_id FOR SHARE;
        IF NEW.score > maximum THEN
            RAISE EXCEPTION 'Score exceeds assessment maximum' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END;
    $function$;
    CREATE TRIGGER assessment_results_score_bounds BEFORE INSERT OR UPDATE ON assessment_results
        FOR EACH ROW EXECUTE FUNCTION validate_result_score();

    CREATE FUNCTION validate_session_eligibility() RETURNS trigger LANGUAGE plpgsql AS $function$
    DECLARE target_section bigint; actual_section bigint;
    BEGIN
        SELECT course_section_id INTO target_section FROM attendance.attendance_sessions WHERE id = NEW.session_id;
        SELECT course_section_id INTO actual_section FROM attendance.enrollments WHERE id = NEW.enrollment_id;
        IF target_section IS NOT NULL AND target_section <> actual_section THEN
            RAISE EXCEPTION 'Enrollment is outside the session section' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END;
    $function$;
    CREATE TRIGGER session_eligibility_section BEFORE INSERT OR UPDATE ON session_eligibility
        FOR EACH ROW EXECUTE FUNCTION validate_session_eligibility();

    CREATE VIEW student_directory AS
        SELECT s.id, s.user_id, s.university_id, u.username, u.full_name, u.email,
               s.level, s.department_id, d.code AS department_code,
               s.department_section_id, ds.number AS section_number
        FROM students s JOIN app_users u ON u.id = s.user_id
        JOIN departments d ON d.id = s.department_id
        JOIN department_sections ds ON ds.id = s.department_section_id;
    CREATE VIEW course_section_directory AS
        SELECT cs.id, cs.offering_id, cs.course_id, c.code AS course_code, c.name AS course_name,
               o.term_id, t.code AS term_code, cs.department_id, d.code AS department_code,
               cs.department_section_id, ds.number AS section_number,
               o.doctor_user_id, doctor.full_name AS doctor_name,
               cs.ta_user_id, ta.full_name AS ta_name,
               (SELECT count(*) FROM enrollments e WHERE e.course_section_id = cs.id AND e.state = 'active') AS student_count
        FROM course_sections cs JOIN courses c ON c.id = cs.course_id
        JOIN course_offerings o ON o.id = cs.offering_id
        JOIN academic_terms t ON t.id = o.term_id
        JOIN departments d ON d.id = cs.department_id
        JOIN department_sections ds ON ds.id = cs.department_section_id
        JOIN app_users doctor ON doctor.id = o.doctor_user_id
        JOIN app_users ta ON ta.id = cs.ta_user_id;

    INSERT INTO schema_migrations(version, description)
        VALUES (1, 'Academic data and attendance, assessment, quiz workflow foundation');
END;
