        max_points numeric(9,2) NOT NULL CHECK (max_points >= 0),
        allocation_mode text NOT NULL CHECK (allocation_mode IN ('fixed', 'normalized', 'proportional')),
        position integer NOT NULL CHECK (position >= 0),
        FOREIGN KEY (policy_id, offering_id) REFERENCES grading_policies(id, offering_id),
        UNIQUE (policy_id, code),
        UNIQUE (policy_id, position),
        UNIQUE (id, offering_id)
