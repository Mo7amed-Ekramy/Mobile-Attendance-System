-- PostgreSQL 14+. Database-owned academic data; no dependency on .NET or Flutter.
-- Safe to replay. Future schema changes must use a new numbered migration.
BEGIN;
CREATE SCHEMA IF NOT EXISTS attendance;
REVOKE ALL ON SCHEMA attendance FROM PUBLIC;
SET LOCAL search_path TO attendance, public;
CREATE TABLE IF NOT EXISTS schema_migrations (
    version integer PRIMARY KEY,
    description text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $migration$
BEGIN
    IF EXISTS (SELECT 1 FROM schema_migrations WHERE version = 1) THEN
        RETURN;
    END IF;

    CREATE TABLE departments (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code text NOT NULL UNIQUE CHECK (btrim(code) <> ''),
        name text NOT NULL CHECK (btrim(name) <> '')
    );
    CREATE TABLE department_sections (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        department_id bigint NOT NULL REFERENCES departments(id),
        number integer NOT NULL CHECK (number > 0),
        UNIQUE (department_id, number),
        UNIQUE (id, department_id)
    );
    CREATE TABLE app_users (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username text NOT NULL CHECK (btrim(username) <> ''),
        full_name text NOT NULL CHECK (btrim(full_name) <> ''),
        email text,
        role text NOT NULL CHECK (role IN ('admin', 'doctor', 'ta', 'student')),
        password_hash text,
        is_active boolean NOT NULL DEFAULT true,
        created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE (id, role),
        CHECK (password_hash IS NULL OR btrim(password_hash) <> '')
    );
    CREATE UNIQUE INDEX app_users_username_unique ON app_users (lower(username));
    CREATE UNIQUE INDEX app_users_email_unique ON app_users (lower(email)) WHERE email IS NOT NULL;

    CREATE TABLE students (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id bigint NOT NULL UNIQUE,
        user_role text GENERATED ALWAYS AS ('student'::text) STORED,
        university_id text NOT NULL UNIQUE CHECK (btrim(university_id) <> ''),
        level integer NOT NULL CHECK (level BETWEEN 1 AND 10),
        department_id bigint NOT NULL REFERENCES departments(id),
        department_section_id bigint NOT NULL,
        FOREIGN KEY (user_id, user_role) REFERENCES app_users(id, role),
        FOREIGN KEY (department_section_id, department_id)
            REFERENCES department_sections(id, department_id)
    );
    CREATE INDEX students_department_section ON students (department_section_id);

    CREATE TABLE academic_terms (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code text NOT NULL UNIQUE,
        name text NOT NULL,
        starts_on date,
        ends_on date,
        is_archived boolean NOT NULL DEFAULT false,
        CHECK (ends_on IS NULL OR starts_on IS NULL OR ends_on >= starts_on)
    );
    CREATE TABLE courses (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code text NOT NULL UNIQUE CHECK (btrim(code) <> ''),
        name text NOT NULL CHECK (btrim(name) <> ''),
        level integer NOT NULL CHECK (level BETWEEN 1 AND 10),
        legacy_semester text
    );
    CREATE TABLE course_departments (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        course_id bigint NOT NULL REFERENCES courses(id),
        department_id bigint NOT NULL REFERENCES departments(id),
        UNIQUE (course_id, department_id)
    );
    CREATE TABLE course_offerings (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        course_id bigint NOT NULL REFERENCES courses(id),
        term_id bigint NOT NULL REFERENCES academic_terms(id),
        doctor_user_id bigint NOT NULL,
        doctor_role text GENERATED ALWAYS AS ('doctor'::text) STORED,
        FOREIGN KEY (doctor_user_id, doctor_role) REFERENCES app_users(id, role),
        UNIQUE (course_id, term_id),
        UNIQUE (id, course_id)
    );
    CREATE INDEX course_offerings_doctor ON course_offerings (doctor_user_id, term_id);
    CREATE TABLE course_sections (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        offering_id bigint NOT NULL,
        course_id bigint NOT NULL,
        department_id bigint NOT NULL,
        department_section_id bigint NOT NULL,
        ta_user_id bigint NOT NULL,
        ta_role text GENERATED ALWAYS AS ('ta'::text) STORED,
        FOREIGN KEY (offering_id, course_id) REFERENCES course_offerings(id, course_id),
        FOREIGN KEY (department_section_id, department_id)
            REFERENCES department_sections(id, department_id),
        FOREIGN KEY (course_id, department_id) REFERENCES course_departments(course_id, department_id),
        FOREIGN KEY (ta_user_id, ta_role) REFERENCES app_users(id, role),
        UNIQUE (offering_id, department_section_id),
        UNIQUE (id, offering_id)
    );
    CREATE INDEX course_sections_ta ON course_sections (ta_user_id, offering_id);
    CREATE TABLE enrollments (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        student_id bigint NOT NULL REFERENCES students(id),
        offering_id bigint NOT NULL REFERENCES course_offerings(id),
        course_section_id bigint NOT NULL,
        state text NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'dropped', 'completed')),
        enrolled_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (course_section_id, offering_id) REFERENCES course_sections(id, offering_id),
        UNIQUE (student_id, offering_id),
        UNIQUE (id, offering_id),
        UNIQUE (id, course_section_id)
    );
    CREATE INDEX enrollments_section ON enrollments (course_section_id, state);

    -- Workflow tables start empty: the legacy JSON does not contain academic results.
    CREATE TABLE grading_policies (
